/// Returns the verse count for [bookId] chapter [chapterNumber] (1-based).
///
/// Throws [StateError] if [bookId] has no entry in [kVerseCountsByBook].
/// Throws [RangeError] if [chapterNumber] is outside 1–chapterCount.
int verseCountForChapter(String bookId, int chapterNumber) {
  final counts = kVerseCountsByBook[bookId];
  if (counts == null) {
    throw StateError(
      'No verse counts for bookId "$bookId". '
      'Add an entry to kVerseCountsByBook in verse_counts.dart.',
    );
  }
  RangeError.checkValueInInterval(
    chapterNumber, 1, counts.length, 'chapterNumber',
    'chapterNumber must be 1–${counts.length} for book "$bookId"',
  );
  return counts[chapterNumber - 1];
}
